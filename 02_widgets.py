"""
=========================================================
【Streamlitで最も重要なルールのまとめ（画面の更新タイミング）】

1. フォームの外側（通常のウィジェット）
- 更新タイミング: スライダーを動かす、文字を打つ、選択肢を変えるなど、操作した「瞬間」
- 使われる場面: リアルタイムにグラフを変化させたい時、条件によって入力欄を出し分けたい時

2. フォームの内側（with st.form:）
- 更新タイミング: 「送信ボタン（st.form_submit_button）」を押した「瞬間」だけ
- 使われる場面: アンケート画面や登録フォームなど、たくさんの項目を一度に入力・確定させたい時
=========================================================
"""

import streamlit as st
import pandas as pd

st.title("Streamlit応用編 第2回：詳細解説付きウィジェットとフォーム")

# ========================================================
# 1. フォームの作成（入力を一時停止し、ボタンで一括送信する仕組み）
# ========================================================
st.write("### 1. 複数のセクションを持つフォーム")
st.write("※フォームの中では、入力を変えてもすぐには画面が更新されません。")

# 【解説】 with st.form(...) について
# withブロック（字下げされている範囲）の中にある入力部品は、すべて「1つのグループ」にまとまります。
# key="detailed_form" は、このフォームのIDです。他のフォームと名前が被らなければ何でもOKです。
with st.form(key="detailed_form"):

    st.write("**基本情報**")

    # 【解説】 st.text_input について
    # 第1引数: 画面に表示されるラベル（質問文）
    # value: 最初から入力欄に入れておく「初期値」
    # 入力された文字は、左側の変数（name）に文字列として代入されます。
    name = st.text_input("名前を入力してください", value="小野 東輝")

    # 【解説】 st.number_input について
    # min_value / max_value: 入力できる数値の下限と上限（これを超えるとエラー表示になる）
    # 入力された数字は、左側の変数（age）に数値として代入されます。
    age = st.number_input(
        "年齢を入力してください", min_value=0, max_value=120, value=23
    )

    st.write("**連絡先情報**")
    email = st.text_input("メールアドレスを入力してください")
    phone = st.text_input("電話番号を入力してください")

    # 【解説】 st.form_submit_button について
    # フォームの中には「必ず1つ」この送信ボタンが必要です。これが無いとエラーになります。
    # ボタンが押されていない時は False、押された瞬間だけ True になります。
    submitted = st.form_submit_button("送信")

# 【解説】 送信後の処理
# with st.form(...) の「外側（字下げを戻した場所）」に書きます。
# submitted が True（送信ボタンが押された）の場合のみ、以下のメッセージを表示します。
if submitted:
    st.success(f"こんにちは、{name}さん。あなたは{age}歳ですね。")
    st.info(f"連絡先情報: {email}, {phone}")

st.divider()  # 画面に区切り線を引きます


# ========================================================
# 2. 動的なUI要素の生成（選択によって画面を切り替える）
# ========================================================
st.write("### 2. 動的なUI要素の生成")
st.write(
    "※ここはフォームの外なので、選択した瞬間に裏側で再読み込みが走り、画面が切り替わります。"
)

# 【解説】 st.selectbox について
# 第2引数のタプル ("テキスト", "画像", ...) の中から選ばせます。
# 選ばれた項目名がそのまま変数（option）に代入されます。
option = st.selectbox(
    "表示する内容を選んでください", ("テキスト", "画像", "データフレーム")
)

# optionの中身（ユーザーが何を選んだか）を条件分岐（if文）で判定して、表示を出し分けます。
if option == "テキスト":
    st.write("これはテキストです。")

elif option == "画像":
    # st.image は画像を表示する機能。ネット上のURLや、パソコン内のファイルパスを指定できます。
    st.image("https://picsum.photos/400/200", caption="ランダムなダミー画像")

elif option == "データフレーム":
    # 辞書型データを使って、テスト用の表（データフレーム）を作成
    df = pd.DataFrame({"列1": [1, 2, 3], "列2": ["A", "B", "C"]})
    st.dataframe(df)

st.divider()


# ========================================================
# 3. 条件に応じたコンテンツ表示（値によって項目を出し入れする）
# ========================================================
st.write("### 3. 条件に応じたコンテンツ表示")

# ここもフォーム外なので、数値を変更した瞬間にプログラムが上から下まで再実行されます。
# key="check_age" は、上のフォーム内にある年齢入力と区別するためのIDです。
check_age = st.number_input(
    "確認用の年齢を入力してください",
    min_value=0,
    max_value=120,
    value=18,
    key="check_age",
)

# 年齢が18以上の時だけ、免許証の入力欄（st.text_input）を画面に描画します。
# 18未満の時は描画の処理がスキップされるため、入力欄が画面から消えたように見えます。
if check_age >= 18:
    st.write("あなたは成人です。")
    license_number = st.text_input("運転免許証の番号を入力してください")
else:
    st.write("未成年のため、追加情報は必要ありません。")
